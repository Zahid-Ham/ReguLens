/**
 * Helper to compute summary metrics and distribution from records
 */
export function getAnalysisSummaryData(records = PSL_CHANGE_RECORDS) {
  const total = records.length
  const substantive = records.filter((r) => r.changeType === 'MODIFIED').length
  const wordingOnly = records.filter((r) => r.changeType === 'WORDING_ONLY').length
  const added = records.filter((r) => r.changeType === 'ADDED_CANDIDATE').length
  const removed = records.filter((r) => r.changeType === 'REMOVED_CANDIDATE').length
  const unchanged = records.filter((r) => r.changeType === 'UNCHANGED').length

  const substantivePct = Math.round((substantive / total) * 100)
  const wordingOnlyPct = Math.round((wordingOnly / total) * 100)
  const addedPct = Math.round((added / total) * 100)
  const removedPct = Math.round((removed / total) * 100)
  const unchangedPct = Math.round((unchanged / total) * 100)

  return {
    total,
    substantive,
    substantivePct,
    wordingOnly,
    wordingOnlyPct,
    added,
    addedPct,
    removed,
    removedPct,
    unchanged,
    unchangedPct,
    chartData: [
      { name: 'Substantive', value: substantive, percentage: substantivePct, color: '#DC2626' }, // Coral/Red
      { name: 'Wording only', value: wordingOnly, percentage: wordingOnlyPct, color: '#D97706' }, // Amber
      { name: 'Added', value: added, percentage: addedPct, color: '#2563EB' }, // Blue
      { name: 'Removed', value: removed, percentage: removedPct, color: '#64748B' }, // Slate Gray
      { name: 'Unchanged', value: unchanged, percentage: unchangedPct, color: '#94A3B8' }, // Light Slate
    ],
  }
}
